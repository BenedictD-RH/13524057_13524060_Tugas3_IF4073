function net = train_model(imds, pxds, splitPath, outputName)
    split = load("output\" + splitPath);
    trainIdx = split.trainIdx;
    valIdx = split.valIdx;
    
    imdsTrain = subset(imds, trainIdx);   pxdsTrain = subset(pxds, trainIdx);
    imdsVal   = subset(imds, valIdx);     pxdsVal   = subset(pxds, valIdx);
    
    tbl = countEachLabel(pxdsTrain);
    freq = tbl.PixelCount ./ sum(tbl.PixelCount);
    w = single(median(freq) ./ freq);
    w = min(w, 5); 
    
    imageSize  = [360 480 3];
    numClasses = 11;
    net = deeplabv3plus(imageSize, numClasses, "resnet18");
    
    dsTrain = combine(imdsTrain, pxdsTrain);
    dsVal   = combine(imdsVal,   pxdsVal);
    
    
    options = trainingOptions("adam", ...
        InitialLearnRate = 3e-4, ...
        GradientThreshold = 1, ... 
        LearnRateSchedule = "piecewise", ...
        LearnRateDropPeriod = 10, ...
        LearnRateDropFactor = 0.5, ...
        MaxEpochs = 30, ...
        MiniBatchSize = 8, ...
        Shuffle = "every-epoch", ...
        ValidationData = dsVal, ...
        ValidationFrequency = 52, ... 
        CheckpointPath = "output\checkpoints", ...
        ExecutionEnvironment = "gpu", ...
        Plots = "training-progress", ...
        Verbose = true);
    
    lossFcn = @(Y,T) maskedCE(Y, T, w);
    [net, info] = trainnet(dsTrain, net, lossFcn, options);
    classNames = pxds.ClassNames;
    save("output\" + outputName, "net", "info", "classNames");
end